"""
PDF reports generated on demand from stored results. Nothing is re-run through AI.
Basic (rule-based) results are labelled as not AI-generated.
"""

from django.utils import timezone

from apps.ai_services.service import SOURCE_BASIC
from apps.interviews.rubric import competency_label
from common.pdf import Document

AI_NOTICE = (
    "AI-generated content. It can be inaccurate or incomplete, and scores are approximate "
    "coaching guidance, not a hiring assessment. Use your own judgement."
)
BASIC_NOTICE = (
    "Basic content (not AI-generated): made by PrepWise's built-in rules (keyword matching, "
    "a question bank and simple answer checks). It can miss context, and scores are a rough "
    "guide, not a hiring assessment. Use your own judgement."
)
MIXED_NOTICE = (
    "Some content is AI-generated and some is basic (made by PrepWise's built-in rules, not "
    "AI); each item is labelled. It can be inaccurate or incomplete, and scores are coaching "
    "guidance, not a hiring assessment. Use your own judgement."
)


def _date(value):
    return timezone.localtime(value).strftime("%d %b %Y, %H:%M") if value else "-"


def _is_basic(source):
    return source == SOURCE_BASIC


def _ai_line(source, provider, model):
    if _is_basic(source):
        return "Basic (not AI-generated): made by PrepWise's built-in rules."
    return f"Generated by PrepWise AI ({model or provider or 'an AI model'})."


def _notice(sources):
    basic = {_is_basic(source) for source in sources}
    if basic == {True}:
        return BASIC_NOTICE
    if basic == {False} or not basic:
        return AI_NOTICE
    return MIXED_NOTICE


def render_analysis_report(analysis):
    doc = Document("Resume analysis report")
    doc.title("Resume analysis report")
    job = analysis.job_profile
    doc.key_values(
        [
            ("Resume", analysis.resume.original_filename),
            ("Job", f"{job.title}{f' at {job.company}' if job.company else ''}"),
            ("Completed", _date(analysis.completed_at)),
        ]
    )
    doc.muted(_notice([analysis.ai_source]))
    doc.muted(_ai_line(analysis.ai_source, analysis.ai_provider, analysis.ai_model))

    doc.heading("Summary")
    doc.paragraph(analysis.summary)

    doc.heading("Skills the resume shows")
    if analysis.matched_skills:
        doc.bullets(f"{item['skill']}: {item['evidence']}" for item in analysis.matched_skills)
    else:
        doc.paragraph("None identified.")

    doc.heading("Gaps to address")
    if analysis.missing_skills:
        doc.bullets(
            f"{item['skill']} ({item['importance']} importance): {item['suggestion']}"
            for item in analysis.missing_skills
        )
    else:
        doc.paragraph("None identified.")

    doc.heading("Recommendations")
    doc.bullets(analysis.recommendations or ["None."])

    doc.heading("Questions to prepare for")
    for index, item in enumerate(analysis.questions, start=1):
        doc.paragraph(f"{index}. {item['question']}")
        doc.muted(f"Focus: {item['focus']}. Why: {item['reason']}")
    return doc.output()


def render_interview_report(session):
    doc = Document("Mock interview report")
    doc.title("Mock interview report")
    evaluations = [
        q.answer.evaluation
        for q in session.questions.all()
        if hasattr(q, "answer") and hasattr(q.answer, "evaluation")
    ]
    average = (
        f"{sum(e.overall_score for e in evaluations) / len(evaluations):.1f} / 5"
        if evaluations
        else "No feedback yet"
    )
    doc.key_values(
        [
            ("Role", session.role_title),
            ("Format", "Voice" if session.mode == "voice" else "Text"),
            ("Started", _date(session.created_at)),
            ("Status", "Completed" if session.status == "completed" else "In progress"),
            ("Questions answered", f"{session.answers.count()} of {session.question_count}"),
            ("Average score", average),
        ]
    )
    doc.muted(_notice([session.ai_source, *(e.ai_source for e in evaluations)]))
    if _is_basic(session.ai_source):
        doc.muted("Questions: basic (not AI-generated), from PrepWise's built-in question bank.")

    for question in session.questions.all():
        doc.heading(f"Question {question.position}")
        doc.paragraph(question.text)
        answer = getattr(question, "answer", None)
        if answer is None:
            doc.muted("Not answered.")
            continue
        label = "Spoken answer (transcribed)" if answer.input_mode == "voice" else "Answer"
        doc.muted(label)
        doc.paragraph(answer.text)
        evaluation = getattr(answer, "evaluation", None)
        if evaluation is None:
            doc.muted("No feedback requested.")
            continue
        doc.muted(
            f"{'Basic feedback' if _is_basic(evaluation.ai_source) else 'AI feedback'}: "
            f"{evaluation.overall_score} / 5. "
            + _ai_line(evaluation.ai_source, evaluation.ai_provider, evaluation.ai_model)
        )
        doc.paragraph(evaluation.summary)
        if evaluation.strengths:
            doc.muted("Strengths")
            doc.bullets(evaluation.strengths)
        if evaluation.improvements:
            doc.muted("To improve")
            doc.bullets(evaluation.improvements)
        scores = list(evaluation.competency_scores.all())
        if scores:
            doc.muted("Competency scores")
            doc.bullets(
                f"{competency_label(s.competency)}: {s.score} / 5. {s.rationale}" for s in scores
            )
    return doc.output()
